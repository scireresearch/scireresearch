    def analyze_packet(self, packet):
        """
        Examines each network packet for AI signatures.
        """
        if self.stop_sniffing.is_set():
            return # Stop processing if event is set

        src_ip = None
        dst_ip = None
        protocol = 'UNKNOWN'
        dst_port = None
        domain = None
        detected_provider = None
        api_key_found = False
        method = 'UNKNOWN'
        confidence = 0.0
        payload_str = ''

        if packet.haslayer(IP):
            src_ip = packet[IP].src
            dst_ip = packet[IP].dst
            protocol = 'TCP' if packet.haslayer(TCP) else ('UDP' if packet.haslayer(UDP) else str(packet[IP].proto))

            if packet.haslayer(TCP):
                dst_port = packet[TCP].dport
            elif packet.haslayer(UDP):
                dst_port = packet[UDP].dport

            # Check for DNS queries to AI domains
            if packet.haslayer(DNS) and packet[DNS].qr == 0:  # DNS Query
                if hasattr(packet[DNS].qd, 'qname'): # Ensure qname exists
                    qname = packet[DNS].qd.qname.decode('utf-8').rstrip('.')
                    for provider, config in self.ai_patterns.items():
                        for dom_pattern in config['domains']:
                            if re.search(dom_pattern, qname):
                                detected_provider = provider
                                domain = qname
                                method = 'DNS_QUERY'
                                confidence = 0.9
                                # print(f"  ✓ Detected {provider} DNS query to {qname}")
                                break
                        if detected_provider: break

            # Check for HTTP/HTTPS traffic (looking for Host header or raw payload)
            if packet.haslayer(Raw):
                try:
                    payload_str = packet[Raw].load.decode('utf-8', errors='ignore')
                    method = 'HTTP_REQUEST'
                    confidence = 0.95
                except UnicodeDecodeError:
                    pass

                # Look for API keys in the raw payload
                for provider, config in self.ai_patterns.items():
                    if config.get('api_key_regex'):
                        matches = re.findall(config['api_key_regex'], payload_str)
                        if matches:
                            api_key_found = True
                            detected_provider = provider # Assign provider if API key found
                            domain = domain or dst_ip # Default to destination IP if no domain from DNS
                            # print(f"  ⚠ API Key detected for {provider} from {src_ip}: {matches[0][:8]}...")
                            break

                # Look for domain patterns in payload (e.g., Host header)
                if not detected_provider:
                    for provider, config in self.ai_patterns.items():
                        for dom_pattern in config['domains']:
                            if re.search(dom_pattern, payload_str):
                                detected_provider = provider
                                domain = domain or dom_pattern.replace('\\.', '.') # Get actual domain from regex
                                # print(f"  ✓ Detected {provider} HTTP traffic from {src_ip}")
                                break
                        if detected_provider: break

        if detected_provider:
            detection_data = {
                'timestamp': datetime.datetime.now().isoformat(),
                'source_ip': src_ip,
                'destination_ip': dst_ip,
                'destination_port': dst_port,
                'protocol': protocol,
                'domain': domain,
                'ai_provider': detected_provider,
                'api_key_found': api_key_found,
                'method': method,
                'confidence': confidence
            }
            self._save_result(detection_data)

    def start_capture(self, interface='eth0', count=0, timeout=None):
        """
        Begins live network monitoring. Uses a threading.Event to stop sniffing.
        """
        self.stop_sniffing.clear()
        print(f"Starting packet capture on interface {interface}...")
        print("Press Ctrl+C to stop.")

        def _sniff_thread():
            sniff(iface=interface, prn=self.analyze_packet, store=0, count=count, timeout=timeout,
                  stop_filter=lambda p: self.stop_sniffing.is_set())
            print("Sniffing thread finished.")

        self.sniff_thread = threading.Thread(target=_sniff_thread)
        self.sniff_thread.start()

        if timeout is not None:
            # Wait for the sniff_thread to finish, or for timeout if it's set
            self.sniff_thread.join(timeout=timeout)
            if self.sniff_thread.is_alive():
                print(f"Capture timed out after {timeout} seconds.")
                self.stop_sniffing.set() # Signal thread to stop
                self.sniff_thread.join() # Wait for thread to terminate

    def stop_capture(self):
        """
        Stops the ongoing packet capture.
        """
        if self.sniff_thread and self.sniff_thread.is_alive():
            print("Stopping packet capture...")
            self.stop_sniffing.set() # Signal the sniff thread to stop
            self.sniff_thread.join() # Wait for the thread to actually stop
            print("Packet capture stopped.")
        else:
            print("No active capture to stop.")

    def process_pcap_file(self, pcap_file_path):
        """
        Reads packets from a .pcap file and processes them using analyze_packet.
        """
        print(f"Processing pcap file: {pcap_file_path}...")
        try:
            packets = rdpcap(pcap_file_path)
            for i, packet in enumerate(packets):
                # Simulate live capture for stop event compatibility (though not strictly necessary for offline)
                if self.stop_sniffing.is_set():
                    print("Pcap processing stopped by signal.")
                    break
                self.analyze_packet(packet)
            print(f"Finished processing {len(packets)} packets from {pcap_file_path}.")
        except FileNotFoundError:
            print(f"Error: Pcap file not found at {pcap_file_path}")
        except Exception as e:
            print(f"An error occurred during pcap processing: {e}")

    def get_shadow_ai_summary(self):
        """
        Returns statistics on detected AI usage.
        """
        conn = sqlite3.connect(self.db_name)
        cursor = conn.cursor()
        summary = {}

        cursor.execute("SELECT COUNT(*) FROM detected_ai_systems")
        summary['total_detections'] = cursor.fetchone()[0]

        cursor.execute("SELECT DISTINCT ai_provider FROM detected_ai_systems")
        summary['detected_providers'] = [row[0] for row in cursor.fetchall()]

        cursor.execute("SELECT ai_provider, COUNT(*) FROM detected_ai_systems GROUP BY ai_provider")
        summary['detections_by_provider'] = cursor.fetchall()

        cursor.execute("SELECT source_ip, COUNT(*) FROM detected_ai_systems GROUP BY source_ip ORDER BY COUNT(*) DESC LIMIT 5")
        summary['top_source_ips'] = cursor.fetchall()

        cursor.execute("SELECT COUNT(DISTINCT source_ip) FROM detected_ai_systems")
        summary['unique_source_ips'] = cursor.fetchone()[0]

        conn.close()
        return summary

    def get_detected_systems(self):
        """
        Returns all detected AI systems from the database.
        """
        conn = sqlite3.connect(self.db_name)
        cursor = conn.cursor()
        cursor.execute("SELECT id, ai_provider, domain, source_ip, timestamp, method, confidence, api_key_found FROM detected_ai_systems ORDER BY timestamp DESC")
        results = cursor.fetchall()
        conn.close()
        return results

