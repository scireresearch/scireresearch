    def initialize_database(self):
        conn = sqlite3.connect(self.db_name)
        cursor = conn.cursor()
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS detected_ai_systems (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp TEXT,
                source_ip TEXT,
                destination_ip TEXT,
                destination_port INTEGER,
                protocol TEXT,
                domain TEXT,
                ai_provider TEXT,
                api_key_found BOOLEAN,
                method TEXT,
                confidence REAL
            )
        ''')
        conn.commit()
        conn.close()

    def _save_result(self, data):
        conn = sqlite3.connect(self.db_name)
        cursor = conn.cursor()
        cursor.execute("INSERT INTO detected_ai_systems (timestamp, source_ip, destination_ip, destination_port, protocol, domain, ai_provider, api_key_found, method, confidence) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                       (data['timestamp'], data['source_ip'], data['destination_ip'], data['destination_port'], data['protocol'], data['domain'], data['ai_provider'], data['api_key_found'], data['method'], data['confidence']))
        conn.commit()
        conn.close()
